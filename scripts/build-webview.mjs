#!/usr/bin/env node
// Generates src/webview/visioOneHtml.ts from src/webview/index.html and the scripts it
// references (src/webview/core.js, every src/features/<slug>/webview.js,
// src/webview/bootstrap.js).
//
// The WebView loads the page as an inline string (see VisioMapView.tsx and
// docs/SDK_NOTES.md): an inline page has no folder to load <script src> files from, so
// this script replaces each <script src="..."></script> tag of index.html with an
// inline <script> holding that file's content, and writes the result as a TypeScript
// string module. Edit index.html and the .js files only. Zero dependencies, plain Node.
//
//   node scripts/build-webview.mjs           regenerate visioOneHtml.ts
//   node scripts/build-webview.mjs --check   exit 1 if visioOneHtml.ts is out of date
//
// Run automatically before `npm start`, `npm run ios`, `npm run android` and
// `npm test`; `npm run lint` runs the --check mode.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webviewDir = join(root, 'src/webview');
const source = join(webviewDir, 'index.html');
const target = join(webviewDir, 'visioOneHtml.ts');

const normalize = (text) => text.replace(/\r\n/g, '\n');

const html = normalize(readFileSync(source, 'utf8')).replace(
  /^([ \t]*)<script src="([^"]+)"><\/script>$/gm,
  (_tag, indent, src) => {
    const script = normalize(readFileSync(join(webviewDir, src), 'utf8')).replace(/\n$/, '');
    if (script.includes('</script')) {
      throw new Error(`${src} contains "</script", which would end the inline <script> early.`);
    }
    return `${indent}<script>\n// ${src}\n${script}\n${indent}</script>`;
  },
);

// One JSON string per line: no escaping hazard (backticks, ${...}, backslashes) and the
// generated file diffs line by line like the sources.
const lines = html.replace(/\n$/, '').split('\n');
const output =
  '// GENERATED by scripts/build-webview.mjs from src/webview/index.html and the scripts\n' +
  '// it references -- do not edit by hand. Edit those files, then run\n' +
  '// `node scripts/build-webview.mjs` (also run automatically before npm start / ios /\n' +
  '// android / test).\n' +
  'export const visioOneHtml = [\n' +
  lines.map((line) => `  ${JSON.stringify(line)},`).join('\n') +
  "\n].join('\\n');\n";

const rel = relative(root, target);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file: reported below
  }
  if (current !== output) {
    console.error(`${rel} is out of date with src/webview/index.html and its scripts: run \`node scripts/build-webview.mjs\`.`);
    process.exit(1);
  }
  console.log(`${rel} is up to date.`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${rel}.`);
}
