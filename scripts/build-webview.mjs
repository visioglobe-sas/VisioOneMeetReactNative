#!/usr/bin/env node
// Generates src/assets/visioOneHtml.ts from src/assets/visioOne.html.
//
// The WebView loads the page as an inline string (see VisioMapView.tsx and
// docs/SDK_NOTES.md), so the page needs to exist as a TypeScript string module.
// visioOne.html is the only file to edit; this script writes the string module from
// it. Zero dependencies, plain Node.
//
//   node scripts/build-webview.mjs           regenerate visioOneHtml.ts
//   node scripts/build-webview.mjs --check   exit 1 if visioOneHtml.ts is out of date
//
// Run automatically before `npm start`, `npm run ios`, `npm run android` and
// `npm test`; `npm run lint` runs the --check mode.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/assets/visioOne.html');
const target = join(root, 'src/assets/visioOneHtml.ts');

const html = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
// One JSON string per line: no escaping hazard (backticks, ${...}, backslashes) and the
// generated file diffs line by line like the page itself.
const lines = html.replace(/\n$/, '').split('\n');
const output =
  '// GENERATED by scripts/build-webview.mjs from visioOne.html -- do not edit by hand.\n' +
  '// Edit src/assets/visioOne.html, then run `node scripts/build-webview.mjs`\n' +
  '// (also run automatically before npm start / ios / android / test).\n' +
  'export const visioOneHtml = [\n' +
  lines.map((line) => `  ${JSON.stringify(line)},`).join('\n') +
  "\n].join('\\n');\n";

const rel = relative(root, target);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file: reported below
  }
  if (current !== output) {
    console.error(`${rel} is out of date with visioOne.html: run \`node scripts/build-webview.mjs\`.`);
    process.exit(1);
  }
  console.log(`${rel} is up to date.`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${rel}.`);
}
